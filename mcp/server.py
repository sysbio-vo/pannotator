"""MCP server for Pannotator. Speaks MCP over stdio, see README.md in this directory.

NOTE: do not turn this directory into a package with an __init__.py, it would shadow the `mcp` SDK
for anything started from the repository root.
"""

from pathlib import Path
from typing import Annotated, Any, Literal

import annotations as gff
import pipeline
from pydantic import Field

from mcp.server import MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from mcp.types import ToolAnnotations

mcp = MCPServer(
    "pannotator",
    version=pipeline.pipeline_version(),
    instructions=(
        "Pannotator annotates collections of bacterial genome assemblies: it predicts CDSs per genome, clusters them, "
        "annotates one representative per cluster with Bakta and propagates the result. Typical order: check_setup to "
        "choose a profile and a Bakta database, validate_inputs, launch_pipeline, then get_run_status until the run is "
        "completed. Runs take minutes to days and continue when this server stops, so do not poll in a tight loop. "
        "If a run fails, read the error in get_run_status and the failed task with get_task_log; after a fix launch "
        "again with the same outdir, finished tasks are reused. Then use summarize_annotations and search_annotations "
        "on the results. All paths must be absolute and refer to the machine this server runs on."
    ),
)

READ_ONLY = ToolAnnotations(read_only_hint=True, open_world_hint=False)

Outdir = Annotated[str | None, Field(description="Directory with Pannotator results. Alternative to run_id")]
RunIdOrNone = Annotated[str | None, Field(description="Run started by this server. Alternative to outdir")]
Samples = Annotated[list[str] | None, Field(description="Restrict to these sample IDs, all by default")]
RunId = Annotated[str, Field(description="Run ID returned by launch_pipeline or list_runs")]
InfileExtension = Annotated[
    str, Field(description="Only files ending in this string are inputs, e.g. '.fa.gz'. Empty: all files in indir")
]


@mcp.tool(annotations=READ_ONLY)
def check_setup() -> dict[str, Any]:
    """Check which Nextflow profiles and Bakta databases can be used on this machine."""
    return pipeline.check_setup()


@mcp.tool(annotations=READ_ONLY)
def validate_inputs(
    indir: Annotated[str, Field(description="Directory of FASTA assemblies, optionally gzipped")],
    infile_extension: InfileExtension = "",
) -> dict[str, Any]:
    """Check the input assemblies: what would be annotated, under which sample IDs, and what would go wrong."""
    result = pipeline.scan_inputs(indir, infile_extension)
    samples = result.pop("samples")
    return {**result, "first_samples": samples[:20], "ready": not result["errors"]}


@mcp.tool(annotations=ToolAnnotations(read_only_hint=False, destructive_hint=True, open_world_hint=True))
def launch_pipeline(
    indir: Annotated[str, Field(description="Directory of FASTA assemblies, optionally gzipped")],
    outdir: Annotated[str, Field(description="Directory for the results, created if needed")],
    infile_extension: InfileExtension = "",
    profile: Annotated[
        Literal["standard", "docker", "singularity", "conda", "sanger_local", "sanger_lsf", "conda_lsf"],
        Field(description="Nextflow profile, see check_setup. 'standard' needs Bakta and MMseqs2 on PATH"),
    ] = "standard",
    run_name: Annotated[str | None, Field(description="Unique run ID, generated by default")] = None,
    resume: Annotated[bool, Field(description="Reuse finished tasks of earlier runs with the same outdir")] = True,
    bakta_db: Annotated[str | None, Field(description="Existing Bakta database. Default: see check_setup")] = None,
    bakta_db_type: Annotated[
        Literal["light", "full"] | None,
        Field(description="Required database type. Pseudogenes are only detected with 'full'"),
    ] = None,
    download_bakta_db: Annotated[
        bool,
        Field(description="Download the default database if missing (light 1.3 GB, full 33.1 GB). Ask the user first"),
    ] = False,
    compliant: Annotated[bool, Field(description="INSDC-compliant output")] = False,
    save_intermediate: Annotated[
        bool, Field(description="Also publish per-genome CDS/RNA predictions, clustering and raw annotations")
    ] = False,
    scratch: Annotated[bool, Field(description="Run tasks in a node-local scratch directory")] = False,
    min_seq_id: Annotated[
        float,
        Field(gt=0, le=1, description="Protein clustering identity. 1.0 clusters identical sequences only"),
    ] = 1.0,
    coverage: Annotated[
        float,
        Field(gt=0, le=1, description="Protein clustering coverage. Use 0.8 when min_seq_id is below 1"),
    ] = 1.0,
    mmseqs_command: Annotated[
        Literal["easy-linclust", "easy-cluster"],
        Field(description="easy-linclust is faster, easy-cluster more sensitive"),
    ] = "easy-linclust",
    user_proteins: Annotated[str | None, Field(description="FASTA of expert proteins for CDS annotation")] = None,
    user_hmms: Annotated[str | None, Field(description="HMMER profiles for CDS annotation")] = None,
    auxiliary_db: Annotated[
        str | None,
        Field(description="Pangenome index (JSON) to reuse annotations from; created by the run if it does not exist"),
    ] = None,
    extend_auxdb: Annotated[
        bool, Field(description="Rewrite an existing auxiliary_db with the annotations of this run added")
    ] = False,
    work_dir: Annotated[
        str | None, Field(description="Nextflow work directory. Default: inside outdir, kept after the run for resume")
    ] = None,
    dry_run: Annotated[bool, Field(description="Only run the checks and return the command")] = False,
) -> dict[str, Any]:
    """Launch Pannotator in the background and return the run ID to follow it with get_run_status.

    Setup and inputs are checked first and nothing is started if there is a problem. Existing results in outdir with
    the same sample IDs are overwritten.
    """
    arguments = dict(locals())
    dry_run = arguments.pop("dry_run")
    record = pipeline.prepare(**arguments)
    result = {key: record[key] for key in ("run_id", "outdir", "command", "params", "warnings")}
    result["n_genomes"] = len(record["samples"])
    if dry_run:
        return {"started": False, **result}
    pipeline.launch(record)
    return {"started": True, **result, "log": str(Path(record["run_dir"]) / "console.log")}


@mcp.tool(annotations=READ_ONLY)
def list_runs(limit: Annotated[int, Field(ge=1, le=200)] = 20) -> dict[str, Any]:
    """List the runs started by this server, latest first, including those from earlier sessions."""
    return {"runs": pipeline.summarize_runs(limit)}


@mcp.tool(annotations=READ_ONLY)
def get_run_status(run_id: RunId) -> dict[str, Any]:
    """Get state, task counts per pipeline process, number of annotated genomes and, for failed runs, the error.

    States: running, cancelling, completed, failed, cancelled, lost (ended without an exit code).
    """
    return pipeline.status(run_id)


@mcp.tool(annotations=READ_ONLY)
def get_run_log(
    run_id: RunId,
    source: Annotated[
        Literal["console", "nextflow"], Field(description="'nextflow' is the detailed debug log of Nextflow itself")
    ] = "console",
    lines: Annotated[int, Field(ge=1, le=1000)] = 100,
) -> dict[str, Any]:
    """Get the last lines of the log of a run."""
    return pipeline.run_log(run_id, source, lines)


@mcp.tool(annotations=READ_ONLY)
def get_task_log(
    run_id: RunId,
    task_hash: Annotated[str, Field(description="Task hash such as 'ab/12cdef', from get_run_status or get_run_log")],
    lines: Annotated[int, Field(ge=1, le=1000)] = 100,
) -> dict[str, Any]:
    """Get script, output and exit code of a single task, to find out why it failed."""
    return pipeline.task_log(run_id, task_hash, lines)


@mcp.tool(annotations=ToolAnnotations(read_only_hint=False, destructive_hint=True, open_world_hint=False))
def cancel_run(
    run_id: RunId,
    force: Annotated[bool, Field(description="Kill at once, only if a normal cancellation did not work")] = False,
) -> dict[str, Any]:
    """Stop an active run. Finished tasks are kept and can be resumed."""
    return pipeline.cancel(run_id, force)


def results_dir(run_id: str | None, outdir: str | None) -> Path:
    if (run_id is None) == (outdir is None):
        raise ToolError("Provide either run_id or outdir")
    if run_id is not None:
        return Path(pipeline.load_record(run_id)["outdir"])
    return pipeline.resolve_path(outdir, "outdir")


@mcp.tool(annotations=READ_ONLY)
def summarize_annotations(
    run_id: RunIdOrNone = None,
    outdir: Outdir = None,
    samples: Samples = None,
    limit: Annotated[int, Field(ge=1, le=200, description="Genomes per call")] = 20,
    offset: Annotated[int, Field(ge=0)] = 0,
) -> dict[str, Any]:
    """Summarize annotated genomes: contigs, length, features by type, hypothetical proteins and pseudogenes."""
    return gff.summarize(results_dir(run_id, outdir), samples, limit, offset)


@mcp.tool(annotations=READ_ONLY)
def search_annotations(
    query: Annotated[str, Field(description="Case-insensitive text, e.g. a gene name, product or accession")],
    run_id: RunIdOrNone = None,
    outdir: Outdir = None,
    field: Annotated[
        Literal["any", "gene", "product", "locus_tag", "dbxref"],
        Field(description="Where to search; 'dbxref' covers accessions such as UniRef or SO"),
    ] = "any",
    exact: Annotated[bool, Field(description="Match the whole value instead of a part of it")] = False,
    feature_type: Annotated[str | None, Field(description="Only this GFF3 feature type, e.g. CDS or tRNA")] = None,
    samples: Samples = None,
    limit: Annotated[int, Field(ge=1, le=500, description="Hits to return; counts always cover all hits")] = 50,
) -> dict[str, Any]:
    """Search the annotations of all genomes of a run, and count the genomes with and without hits.

    A gene without hits may still be present under another name or on a contig break, so absence is not proven.
    """
    return gff.search(results_dir(run_id, outdir), query, field, exact, feature_type, samples, limit)


@mcp.resource("pannotator://readme", mime_type="text/markdown")
def readme() -> str:
    """Pannotator documentation: parameters, clustering, reuse of annotations, output files."""
    return (pipeline.PIPELINE_DIR / "README.md").read_text()


if __name__ == "__main__":
    mcp.run()
